import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, realpath, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import os from 'node:os';
import { createPlan } from '../scripts/plan.mjs';
import { generateProject } from '../scripts/generate.mjs';
import { collectSelection } from '../scripts/compose.mjs';
const componentsRoot = new URL('../components/', import.meta.url).pathname;
test('Phaser plans combine React UI with games and requested communication', async () => {
  const web = await createPlan(componentsRoot, { configuration: 'web-phaser' });
  assert.equal(web.packages.get('phaser').version, '4.2.1');
  for (const pkg of ['react', 'react-dom', '@vitejs/plugin-react']) assert.equal(web.packages.has(pkg), true);
  assert.equal(web.packages.has('electron'), false);
  for (const file of web.files.keys()) assert.ok(!file.startsWith('src/backend/') && !file.startsWith('src/preload/'));
  assert.equal(web.files.get('src/frontend/core/di/diProvider.tsx').owner, 'react-common');
  assert.equal(web.files.has('src/frontend/components/game/game.component.tsx'), true);
  assert.equal(web.files.has('src/frontend/main.ts'), false);
  assert.match(web.files.get('src/frontend/main.tsx').bytes.toString(), /GameComponent/);
  assert.equal(web.files.get('scripts/renderer.mjs').owner, 'react-common');
  assert.equal(web.files.has('src/frontend/apis/http.api.ts'), false);
  assert.equal(web.files.has('src/frontend/core/di/di.ts'), true);
  const http = await createPlan(componentsRoot, { configuration: 'web-phaser', communications: ['http'] });
  assert.equal(http.files.has('src/frontend/apis/http.api.ts'), true);
  assert.equal(http.environment.has('PUBLIC_API_BASE_URL'), true);
  const desktop = await createPlan(componentsRoot, { configuration: 'electron-phaser', communications: ['http'] });
  assert.deepEqual(desktop.configuration.communications.backend.map(item => item.protocol), ['http', 'ipc']);
  assert.equal(desktop.files.get('scripts/webTarget.mjs').previousOwner, 'phaser');
  assert.equal(desktop.files.has('src/frontend/apis/ipc.api.ts'), true);
  assert.equal(desktop.files.has('src/frontend/apis/http.api.ts'), false);
  const react = await createPlan(componentsRoot, { configuration: 'web-app' });
  assert.equal(react.packages.has('phaser'), false);
  assert.equal(react.files.has('src/frontend/components/game/game.component.tsx'), false);
  assert.equal(react.files.get('src/frontend/core/di/diProvider.tsx').owner, 'react-common');
  assert.equal(react.files.get('src/frontend/core/di/lifecycle.ts').owner, 'frontend-common');
});
test('Phaser dialog keeps IPC required and asks the name after feature selection', async () => {
 const answers = ['6', '', 'none', 'game-app', 'y']; const questions = [];
 const input = await collectSelection(async question => { questions.push(question); return answers.shift(); }, () => {});
 assert.deepEqual(input.selection.communications, ['ipc']);
 assert.equal(input.name, 'game-app'); assert.match(questions.at(-2), /이름/);
 assert.equal(questions.some(question => question.includes('자동 시작')), false);
});
const parent = await realpath(await mkdtemp(path.join(os.tmpdir(), 'composer-phaser-unit-')));
const { app } = await generateProject({ parent, name: 'game', selection: { configuration: 'web-phaser', communications: ['http'] }, verify: false });
test('Phaser manifest is owned by the selected base and records the shared component', async () => {
 const state = JSON.parse(await readFile(path.join(app, '.composer/state.json'), 'utf8'));
 assert.equal(state.files['src/frontend/core/di/features.manifest.ts'].owner, 'phaser');
 assert.equal(state.pendingComponents.some(item => item.id === 'frontend-common'), true);
});
